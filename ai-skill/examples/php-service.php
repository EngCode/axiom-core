//=====> Sizing & String Utility Helpers <=====//

//====> Pixel to REM Converter <====//
if (!function_exists('px_to_rem')) :
    /**
     * Convert pixel integer to REM string
     * @param int|float $pixels
     * @param int $base
     * @return string
    */
    function px_to_rem($pixels, $base = PHENIX_BASE_FONT_SIZE) {
        //===> Guard Clause: Invalid Input <===//
        if (!is_numeric($pixels)) return "0rem";

        //===> Compute Value <===//
        $rem = round((float)$pixels / (int)$base, 4);
        return "{$rem}rem";
    }
endif;

//====> Column Size Suffix Renderer (Symmetric with JS/Python) <====//
if (!function_exists('col_size_handler')) :
    /**
     * Format grid column suffix
     * @param int $size
     * @return string
    */
    function col_size_handler($size) {
        $size = (int) $size;

        //===> Guard Clause: Auto Column <===//
        if ($size === 0) return "-auto";

        //===> Guard Clause: Full Width / Exceeded <===//
        if ($size > 12) return "";

        //===> Standard Column Fraction <===//
        return "-{$size}";
    }
endif;

//=====> Modular Content Sanitizer Service Class <=====//

if (!class_exists('Phenix_Content_Sanitizer')) :
    class Phenix_Content_Sanitizer {
        /**
         * @var array Configuration options
        */
        private static $options = array(
            'strip_empty_tags'    => true,
            'remove_redundant_id' => true,
            'clean_cf7_markup'    => true,
        );

        /**
         * Initialize hooks and configuration
         * @param array $user_options
         * @return void
        */
        public static function init($user_options = array()) {
            //===> Merge Options <===//
            self::$options = array_merge(self::$options, $user_options);
        }

        /**
         * Sanitize and strip bloat from HTML string
         * @param string $content
         * @return string
        */
        public static function clean($content) {
            //===> Guard Clause: Empty Content <===//
            if (empty($content) || !is_string($content)) {
                return '';
            }

            //===> Step 1: Remove Redundant Form Control Wrappers <===//
            if (self::$options['clean_cf7_markup']) {
                $content = self::strip_control_wrappers($content);
            }

            //===> Step 2: Strip Unnecessary Element IDs <===//
            if (self::$options['remove_redundant_id']) {
                $content = self::strip_empty_ids($content);
            }

            //===> Step 3: Strip Empty Containers <===//
            if (self::$options['strip_empty_tags']) {
                $content = self::strip_empty_elements($content);
            }

            //===> Return Clean Output <===//
            return trim($content);
        }

        //====> Strip Control Wrappers <====//
        private static function strip_control_wrappers($markup) {
            //===> Guard: Empty <===//
            if (empty($markup)) return '';

            //===> Regex Replacement <===//
            $pattern = '/<(span).*?class="\s*(?:.*\s)?(?:wpcf7-form-control-wrap|bloat-wrap)(?:\s[^"]+)?\s*"[^\>]*>(.*)<\/\1>/i';
            return preg_replace($pattern, '\2', $markup);
        }

        //====> Strip Empty IDs <====//
        private static function strip_empty_ids($markup) {
            //===> Guard: Empty <===//
            if (empty($markup)) return '';

            //===> Remove Empty or Autogenerated IDs <===//
            return preg_replace('/id="(?:menu-item-\d+|)"/U', '', $markup);
        }

        //====> Strip Empty Elements <====//
        private static function strip_empty_elements($markup) {
            //===> Guard: Empty <===//
            if (empty($markup)) return '';

            //===> Remove Empty Divs/Spans Without Attributes <===//
            return preg_replace('/<(div|span)>\s*<\/\1>/i', '', $markup);
        }
    }
endif;

//=====> Public Helper Functions <=====//

if (!function_exists('phenix_clean_markup')) :
    /**
     * Clean and strip bloat from markup string
     * @param string $content
     * @param array $options
     * @return string
    */
    function phenix_clean_markup($content, $options = array()) {
        //===> Guard Clause <===//
        if (empty($content)) return '';

        //===> Configure and Execute <===//
        Phenix_Content_Sanitizer::init($options);
        return Phenix_Content_Sanitizer::clean($content);
    }
endif;
